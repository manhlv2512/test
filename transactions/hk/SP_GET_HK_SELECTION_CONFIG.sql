create or replace PROCEDURE SP_GET_HK_SELECTION_CONFIG (
  P_TRANSACTION_TYPE OUT SYS_REFCURSOR,
  P_STATUS OUT SYS_REFCURSOR
)
AS
BEGIN

  OPEN P_TRANSACTION_TYPE FOR
    SELECT
      CODE AS VALUE,
      NAME AS LABEL
    FROM GNCN_TRANSACTION_TYPE
    WHERE USE_STATUS = 1 AND LEVEL_TYPE = 1
    ORDER BY ID ASC;

  OPEN P_STATUS FOR
    SELECT
      CODE AS VALUE,
      NAME AS LABEL
    FROM GNCN_CONFIG_COMMONS
    WHERE STATUS = 1 AND SCOPE = 'HKCN_STATUS'
    ORDER BY ID ASC;

END SP_GET_HK_SELECTION_CONFIG;